// Bundles the vendored Generative UI renderer into client/genui-kit.generated.ts, one module the
// client loads when a reply holds a `ui` block. The host's own build compiles the module with the
// rest of the client; its imports (react, react-native, the plugin SDK) are the host's. `--check`
// writes nothing and fails when the committed file is not what the build makes.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "vendor", "genui");
const OUT = path.join(ROOT, "client", "genui-kit.generated.ts");

const manifest = JSON.parse(readFileSync(path.join(DIR, "MANIFEST.json"), "utf8"));
// A `/*!` comment is a legal comment: minifying keeps it. The notice states the change (Apache-2.0
// section 4(b)): the loaders are replaced and the files are bundled and minified.
const banner = [
  "// @ts-nocheck",
  "// Generated by scripts/build-genui.mjs from vendor/genui. Do not edit.",
  `/*! Generative UI renderer, ${manifest.upstream.repository} at ${manifest.upstream.commit}`,
  "Copyright the paseo-plugin-genui and bb-plugin-genui authors. Apache License, Version 2.0: the",
  "licence text is in paseo-office's LICENSE and in vendor/genui/LICENSE.",
  "Changes: bundled and minified with paseo-office's own entry point; upstream's client/loaders.ts is",
  "replaced by vendor/genui/loaders.ts; imports of the SDK's client/react-native read client/ui. No",
  "other file is altered.",
  "*/",
].join("\n");

const result = await build({
  banner: { js: banner },
  entryPoints: [path.join(DIR, "entry.tsx")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2020",
  jsx: "automatic",
  mainFields: ["module", "main"],
  external: ["react", "react/jsx-runtime", "react-native", "zod"],
  plugins: [
    {
      name: "genui-loaders",
      setup(b) {
        // Upstream's components import "../loaders" (and its live-ui "./loaders", not bundled).
        b.onResolve({ filter: /^\.{1,2}\/loaders$/ }, () => ({
          path: path.join(DIR, "loaders.ts"),
        }));
        // The host supplies the plugin SDK. Upstream imports its deprecated `client/react-native`
        // entry, which only re-exports `client/ui`; the office imports `client/ui` itself.
        b.onResolve({ filter: /^@getpaseo\/plugin\/client(\/react-native|\/ui)?$/ }, (args) => ({
          path: args.path.endsWith("/react-native") ? "@getpaseo/plugin/client/ui" : args.path,
          external: true,
        }));
      },
    },
  ],
  minify: true,
  write: false,
  logLevel: "silent",
});
const script = result.outputFiles[0]?.text;
if (!script) throw new Error("No module was built from vendor/genui/entry.tsx");

const text = script;

const name = path.relative(ROOT, OUT);
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text)
    throw new Error(name + " is stale: run npm run build:genui");
  console.log(name + " is up to date");
} else {
  writeFileSync(OUT, text);
  console.log("wrote " + name, Buffer.byteLength(text), "bytes");
}
