// Bundles the vendored scene into one browser script and writes it as a string in
// server/world.generated.ts, so the plugin's server carries it. `--check` writes nothing and
// fails when the committed file is not what the build makes.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { assertPlain, loadLocale, loadOurs, otherLanguages } from "./locale-words.mjs";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = path.join(ROOT, "vendor", "my-office", "src", "office", "paseo-entry.js");
const OUT = path.join(ROOT, "server", "world.generated.ts");
const LICENSE = path.join(ROOT, "vendor", "my-office", "LICENSE");

// my-office's notice, read from its licence file so the two cannot drift. A `/*!` comment is a
// legal comment: minifying keeps it. three.js's own `@license` comment stays where esbuild puts it.
const licence = readFileSync(LICENSE, "utf8").trim();
if (licence.includes("*/")) throw new Error(`${LICENSE} would end the banner's comment`);
const banner = `/*! my-office, https://github.com/khanh020905/my-office\n\n${licence}\n*/`;

const result = await build({
  banner: { js: banner },
  entryPoints: [ENTRY],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  write: false,
  logLevel: "silent",
});
const script = result.outputFiles[0]?.text;
if (!script) throw new Error(`No script was built from ${ENTRY}`);

// JSON.stringify output is a valid TypeScript string literal except for these two line separators.
const literal = JSON.stringify(script)
  .replaceAll("\u2028", "\\u2028")
  .replaceAll("\u2029", "\\u2029");

const module = [
  "// Generated by scripts/build-world.mjs from vendor/my-office. Do not edit.",
  "/** The page script that draws the 3D office: one self-contained browser script. */",
  `export const WORLD_SCRIPT: string = ${literal};`,
  "",
].join("\n");

const kit = readFileSync(path.join(ROOT, "vendor/my-office/assets/vehicles/cars.json"), "utf8");
const kitOut = path.join(ROOT, "server/street-kit.generated.ts");
const kitModule =
  "// Generated by scripts/build-world.mjs. Kenney Car Kit (CC0).\nexport const STREET_KIT: string = " +
  JSON.stringify(kit) +
  ";\n";
// The words of each language but English, one JSON text each: { dict, ours? }. The server sends the one a device asks
// for; the scene carries English only. A locale is plain data: the build refuses a function.
const words = {};
for (const language of otherLanguages()) {
  const dict = await loadLocale(language);
  assertPlain(dict, language);
  const ours = await loadOurs(language);
  if (ours !== null) assertPlain(ours, language);
  words[language] = JSON.stringify(ours === null ? { dict } : { dict, ours });
}
const wordsLiteral = JSON.stringify(words)
  .replaceAll("\u2028", "\\u2028")
  .replaceAll("\u2029", "\\u2029");
const wordsModule = [
  "// Generated by scripts/build-world.mjs from vendor/my-office/src/i18n/locales. Do not edit.",
  "/** The 3D office's words in each language but English, as JSON text a device asks the server for. */",
  `export const WORLD_WORDS: Readonly<Record<string, string>> = ${wordsLiteral};`,
  "",
].join("\n");
const WORDS_OUT = path.join(ROOT, "server", "words.generated.ts");

for (const [file, contents] of [
  [OUT, module],
  [kitOut, kitModule],
  [WORDS_OUT, wordsModule],
]) {
  const name = path.relative(ROOT, file);
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== contents)
      throw new Error(name + " is stale: run npm run build:world");
    console.log(name + " is up to date");
  } else {
    writeFileSync(file, contents);
    console.log("wrote " + name);
  }
}
for (const [language, text] of Object.entries(words))
  console.log(language, Buffer.byteLength(text), "bytes");
